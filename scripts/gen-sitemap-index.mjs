#!/usr/bin/env node
/**
 * The sitemap index, derived from the sitemaps it points at.
 *
 * WHY IT IS GENERATED AND NOT WRITTEN
 * It was a hand-written file: nothing produced it, and its three <lastmod>
 * values were frozen at the day it was written while the sitemaps it points
 * at kept changing. It is the file that is submitted to Search Console, and
 * it was the one file in the chain nobody maintained -- which is the drift
 * its own comment warns about.
 *
 * So each child's <lastmod> is the newest <lastmod> inside that child. The
 * index cannot claim "nothing changed here" when something did, and a child
 * that is not in the build is not listed at all.
 *
 * Run: node scripts/gen-sitemap-index.mjs
 */
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const SITE = process.cwd();
const OUT = join(SITE, 'out');
const PUBLIC = join(SITE, 'public');
const ORIGIN = 'https://shenhezhongke.com';

const CHILDREN = ['sitemap.xml', 'sitemap-ai.xml', 'sitemap-images.xml'];

/** The newest <lastmod> inside a sitemap; the file's own date if it has none. */
function newestLastmod(path) {
  try {
    const raw = readFileSync(path, 'utf8');
    const dates = [...raw.matchAll(/<lastmod>([^<]+)<\/lastmod>/g)].map((m) => m[1].trim());
    if (dates.length) return dates.sort().pop();
  } catch {
    /* fall through to the file's date */
  }
  try {
    return statSync(path).mtime.toISOString().slice(0, 10);
  } catch {
    return null;
  }
}

const entries = [];
for (const name of CHILDREN) {
  const path = join(OUT, name);
  if (!existsSync(path)) {
    console.log(`  skipped ${name}  (not in the build)`);
    continue;
  }
  const lastmod = newestLastmod(path);
  if (!lastmod) continue;
  entries.push({ name, lastmod });
}

if (!entries.length) {
  console.error('  no sitemap to index — nothing written.');
  process.exit(1);
}

const body = entries
  .map(
    (e) =>
      `  <sitemap>\n    <loc>${ORIGIN}/${e.name}</loc>\n    <lastmod>${e.lastmod}</lastmod>\n  </sitemap>`,
  )
  .join('\n');

const xml =
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<!-- GENERATED by scripts/gen-sitemap-index.mjs — do not hand-edit.\n` +
  `     The index of the site's sitemaps. Each <lastmod> is the newest date\n` +
  `     inside that sitemap, so the index cannot say "nothing changed here"\n` +
  `     when something did. -->\n` +
  `<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</sitemapindex>\n`;

for (const dir of [PUBLIC, OUT]) {
  if (existsSync(dir)) writeFileSync(join(dir, 'sitemap-index.xml'), xml, 'utf8');
}
console.log(`  sitemap-index.xml: ${entries.length} sitemaps — ${entries.map((e) => e.name + ' ' + e.lastmod).join(', ')}`);
